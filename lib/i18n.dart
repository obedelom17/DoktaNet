import 'package:flutter/foundation.dart';
import 'package:shared_preferences/shared_preferences.dart';

/// Langue de l'application (fr / en), mémorisée sur l'appareil.
class L10n extends ChangeNotifier {
  String lang = 'fr';
  bool get en => lang == 'en';

  Future<void> load() async {
    final p = await SharedPreferences.getInstance();
    lang = p.getString('lang') == 'en' ? 'en' : 'fr';
  }

  Future<void> toggle() async {
    lang = en ? 'fr' : 'en';
    notifyListeners();
    final p = await SharedPreferences.getInstance();
    await p.setString('lang', lang);
  }
}

final l10n = L10n();

/// Traduit une clé française. Placeholders : `tr("Bonjour {n}", {"n": nom})`.
String tr(String fr, [Map<String, Object?>? params]) {
  var s = fr;
  if (l10n.en) {
    final t = _en[fr];
    if (t != null) {
      s = t;
    } else if (fr.startsWith('Erreur')) {
      s = 'Error${fr.substring(6)}';
    }
  }
  if (params != null) {
    params.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
  }
  return s;
}

